-- A Supabase auth ban prevents future sessions but an already-issued JWT can
-- remain valid until expiry. Put the repeat-infringer decision in the RLS path
-- as well so termination takes effect immediately for private audio access.
create schema if not exists sj_private;
revoke all on schema sj_private from public, anon;
grant usage on schema sj_private to authenticated, service_role;

create or replace function sj_private.copyright_account_allowed(p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select not exists (
    select 1
    from jukebox.copyright_account_actions action
    where action.target_user_id = p_user_id
      and action.action_type = 'termination'
      and action.active
  );
$function$;

revoke all on function sj_private.copyright_account_allowed(uuid) from public, anon;
grant execute on function sj_private.copyright_account_allowed(uuid) to authenticated, service_role;

drop policy if exists track_audio_select_own on jukebox.track_audio;
drop policy if exists track_audio_insert_own_private on jukebox.track_audio;
drop policy if exists track_audio_update_own_private on jukebox.track_audio;
drop policy if exists track_audio_delete_own on jukebox.track_audio;

create policy track_audio_select_own
on jukebox.track_audio
for select
to authenticated
using (
  (select auth.uid()) = uploaded_by
  and sj_private.copyright_account_allowed((select auth.uid()))
);

create policy track_audio_insert_own_private
on jukebox.track_audio
for insert
to authenticated
with check (
  (select auth.uid()) = uploaded_by
  and is_public = false
  and sj_private.copyright_account_allowed((select auth.uid()))
);

create policy track_audio_update_own_private
on jukebox.track_audio
for update
to authenticated
using (
  (select auth.uid()) = uploaded_by
  and sj_private.copyright_account_allowed((select auth.uid()))
)
with check (
  (select auth.uid()) = uploaded_by
  and is_public = false
  and sj_private.copyright_account_allowed((select auth.uid()))
);

-- Retain owner deletion so a terminated user can still request or perform data
-- erasure; SELECT/playback and all new writes remain blocked.
create policy track_audio_delete_own
on jukebox.track_audio
for delete
to authenticated
using ((select auth.uid()) = uploaded_by);

drop policy if exists "jukebox audio read own" on storage.objects;
drop policy if exists "jukebox audio upload own folder" on storage.objects;
drop policy if exists "jukebox audio delete own" on storage.objects;

create policy "jukebox audio read own"
on storage.objects
for select
to authenticated
using (
  bucket_id = 'jukebox-audio'
  and owner_id = (select auth.uid()::text)
  and sj_private.copyright_account_allowed((select auth.uid()))
);

create policy "jukebox audio upload own folder"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'jukebox-audio'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
  and sj_private.copyright_account_allowed((select auth.uid()))
);

create policy "jukebox audio delete own"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'jukebox-audio'
  and owner_id = (select auth.uid()::text)
);
